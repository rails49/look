// Writes dist/look.css: Shoelace's light theme, its dark theme switched on by
// the OS setting, the chrome's tokens and the theme layer's Shoelace values.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { SHOELACE_VALUES, tokenDeclarations } from '../src/tokens.ts';

const themes = createRequire(import.meta.url).resolve('@shoelace-style/shoelace/dist/themes/light.css');
const light = readFileSync(themes, 'utf8');
const dark = readFileSync(themes.replace(/light\.css$/, 'dark.css'), 'utf8');

// The dark theme's first rule holds its values; the rest repeats the light theme's.
const darkValues = dark.slice(dark.indexOf('{') + 1, dark.indexOf('}'));
const shoelaceValues = Object.entries(SHOELACE_VALUES)
  .map(([name, value]) => `  ${name}: ${value};`)
  .join('\n');

const css = `/* @rails49/look. Link once per page. Generated by scripts/build-css.ts. */

${light}
@media (prefers-color-scheme: dark) {
  :root {${darkValues}}
}

:root {
${tokenDeclarations.replace(/^/gm, '  ')}
${shoelaceValues}
}
`;

writeFileSync(new URL('../dist/look.css', import.meta.url), css);
